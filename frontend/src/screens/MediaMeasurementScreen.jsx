function Heatmap({ data }) {
  const rows = Array.isArray(data) ? data : []
  const max = useMemo(() => {
    let m = 0
    rows.forEach((r) => r.data?.forEach((c) => { if (c.count > m) m = c.count }))
    return m || 1
  }, [rows])
  if (!rows.length) return <Empty />
  return (
    <div className="heatmap">
      <div className="heatmap__row heatmap__row--head">
        <span className="heatmap__day" />
        {Array.from({ length: 24 }).map((_, h) => (
          <span key={h} className="heatmap__hcell">{h % 6 === 0 ? `${h}h` : ''}</span>
        ))}
      </div>
      {rows.map((r) => (
        <div className="heatmap__row" key={r.day}>
          <span className="heatmap__day">{r.day.slice(0, 3)}</span>
          {r.data.map((c) => (
            <span
              key={c.hour}
              className="heatmap__cell"
              title={`${r.day} ${c.hour}:00 · ${c.count} article${c.count === 1 ? '' : 's'}`}
              style={{ background: c.count ? `rgba(99,102,241,${0.15 + 0.85 * (c.count / max)})` : 'var(--surface-2)' }}
            />
          ))}
        </div>
      ))}
      {/* Scale legend — the color intensity alone isn't decodable without it. */}
      <div className="heatmap__legend">
        <span className="heatmap__legtxt">Less</span>
        {[0.15, 0.4, 0.65, 0.9].map((o) => (
          <span key={o} className="heatmap__legcell" style={{ background: `rgba(99,102,241,${o})` }} />
        ))}
        <span className="heatmap__legtxt">More · up to {nf(max)}/hr</span>
      </div>
    </div>
  )
}

