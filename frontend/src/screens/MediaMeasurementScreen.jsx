// Peak / lowest day chips + any LLM per-date insights, for time-series charts.
function DateInsights({ series, valueKey = 'count', dateInsights = [] }) {
  const stats = useMemo(() => {
    if (!Array.isArray(series) || series.length === 0) return null
    let hi = series[0]
    let lo = series[0]
    let sum = 0
    for (const d of series) {
      const v = Number(d[valueKey]) || 0
      sum += v
      if (v > (Number(hi[valueKey]) || 0)) hi = d
      if (v < (Number(lo[valueKey]) || 0)) lo = d
    }
    return { hi, lo, avg: sum / series.length }
  }, [series, valueKey])

  if (!stats && (!dateInsights || dateInsights.length === 0)) return null

  return (
    <div className="dateins">
      {stats && (
        <div className="dateins__chips">
          <span className="dateins__chip dateins__chip--hi">
            ▲ Peak · {fmtDate(stats.hi.date)} · {nf(stats.hi[valueKey])}
          </span>
          <span className="dateins__chip dateins__chip--lo">
            ▼ Lowest · {fmtDate(stats.lo.date)} · {nf(stats.lo[valueKey])}
          </span>
          <span className="dateins__chip">~ Avg · {stats.avg.toFixed(1)} / day</span>
        </div>
      )}
      {dateInsights?.map((di, i) => (
        <div className="dateins__card" key={i}>
          <div className="dateins__cardhead">
            <span className="dateins__date">{fmtDate(di.date)}</span>
            {di.pattern_type && <span className="dateins__tag">{di.pattern_type}</span>}
          </div>
          <p className="dateins__summary"><Rich text={di.summary} /></p>
          <div className="dateins__meta">
            {di.peak_day && <span>Peak: {di.peak_day}</span>}
            {di.avg && <span>Avg: {di.avg}</span>}
          </div>
        </div>
      ))}
    </div>
  )
}

