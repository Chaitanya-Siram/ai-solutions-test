// Split a storyboard title into a lead sentence + an italic accent remainder, e.g.
// "Research led the agenda. Regulatory close behind." → lead + em.
function splitHeadline(title) {
  if (!title) return { lead: '', em: '' }
  const m = String(title).match(/^(.*?[.!?])\s+(.+)$/)
  return m ? { lead: m[1], em: m[2] } : { lead: title, em: '' }
}

